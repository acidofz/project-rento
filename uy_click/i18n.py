def t(key: str) -> rx.Var:
    """Return a reactive Var that resolves to the translation in the active language."""
    ru_val = RU.get(key, key)
    en_val = EN.get(key, key)
    uz_val = UZ.get(key, key)
    return rx.cond(
        LangState.lang == "ru",
        ru_val,
        rx.cond(LangState.lang == "uz", uz_val, en_val),
    )
